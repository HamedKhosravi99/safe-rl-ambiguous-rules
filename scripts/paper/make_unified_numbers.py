"""P0-A + P0-E: the semantic-accounting table and the headline-number block.

P0-A  ONE machine-readable table with, for every semantic metric:
      campaign_id, population, denominator, conditioning event, scorer_id,
      generator_version, split_id, n, value, CI.
      Emitted to results/paper/semantic_accounting.{csv,json} and
      paper/generated/gen_semantic_accounting.tex.
      The point of the table is that these quantities are NOT comparable:
      each row states the population it was measured on, and the plan's rule
      is that no two rows may be placed on the same algebraic line unless
      this generator asserts identical populations (assert_same_population).

P0-E  EVERY empirical headline macro used in the unified main text, emitted
      from archived run files into paper/generated/gen_unified_numbers.tex.
      Any quantity this script cannot source raises, so the final build
      cannot contain an unresolved number.

Run: python3 paper/make_unified_numbers.py
"""
from __future__ import annotations

import csv
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GEN = os.path.join(ROOT, "paper", "generated")
ACC_DIR = os.path.join(ROOT, "results", "paper")


def load(*parts):
    p = os.path.join(ROOT, *parts)
    if not os.path.exists(p):
        raise SystemExit(f"P0-E: required archive missing: {p}")
    return json.load(open(p))


def dig(d, path):
    for k in path.split("/"):
        if k:
            d = d[k]
    return d


def write(name, text):
    os.makedirs(GEN, exist_ok=True)
    with open(os.path.join(GEN, name), "w") as fh:
        fh.write("% AUTO-GENERATED by paper/make_unified_numbers.py -- do not edit\n")
        fh.write(text)
    print("wrote", os.path.join(GEN, name))


def mac(name, value):
    return "\\newcommand{\\" + name + "}{" + str(value) + "}\n"


def pct(x, nd=1):
    return f"{100.0 * float(x):.{nd}f}\\%"


