def semantic_accounting():
    e0 = load("results/conformal", "e0", "e0_report.json")
    v4 = load("results/e2e", "e2e_report_v4.json")
    v6 = load("results/e2e", "v6_calibrated.json")
    ext = load("results/conformal", "benchmark_sg", "report_extension.json")

    t4 = dig(v4, "modes/complete/test")
    V4GEN = ("catalog v4 (non-rule repository files only) + frozen v3 "
             "lexical generator, 64 candidates")
    rows = [
        dict(campaign_id="E0-T (prospective, registered)",
             metric="target-blind generator recall",
             population="one hash-selected representative rule per untouched "
                        "E0-T source-file cluster",
             denominator="representatives of untouched test clusters",
             conditioning="none (NOT conditioned on DSL-expressibility)",
             scorer_id="S-det frozen, qhat_sem=0.3462 at level 0.9012",
             generator_version="E0 target-independent generator over the E0-D vocabulary",
             split_id="HMAC path-hash 80 cal / 31 test clusters",
             n=e0["n_test_clusters"],
             value=dig(e0, "generator_secondary/recall"),
             ci=None),
        dict(campaign_id="V4 catalog",
             metric="generator recall (target in candidate pool)",
             population="frozen cross-organization e2e test split",
             denominator="grammar-reachable (DSL-expressible) test units",
             conditioning="target expressible in the DSL",
             scorer_id="frozen v3 weights, dsl_hash 42e29a62, delta_sem=0.10, qhat=0.4847",
             generator_version=V4GEN,
             split_id="cluster bootstrap over 464 test clusters, 2000 resamples",
             n=t4["n_grammar_reachable"],
             value=dig(t4, "rho_gen/point"),
             ci=[dig(t4, "rho_gen/lo"), dig(t4, "rho_gen/hi")]),
        dict(campaign_id="V4 catalog",
             metric="retention given generation",
             population="frozen cross-organization e2e test split",
             denominator="test units whose target was expressible AND generated",
             conditioning="expressible AND generated",
             scorer_id="frozen v3 weights, dsl_hash 42e29a62, delta_sem=0.10, qhat=0.4847",
             generator_version=V4GEN,
             split_id="cluster bootstrap over 464 test clusters, 2000 resamples",
             n=t4["n_in_dsl"],
             value=dig(t4, "rho_ret_given_gen/point"),
             ci=[dig(t4, "rho_ret_given_gen/lo"), dig(t4, "rho_ret_given_gen/hi")],
             conditions_on="V4 catalog/generator recall (target in candidate pool)"),
        dict(campaign_id="V4 catalog",
             metric="end-to-end retained target, whole population",
             population="frozen cross-organization e2e test split",
             denominator="ALL test units, including parser failures and "
                         "out-of-DSL expressions",
             conditioning="none",
             scorer_id="frozen v3 weights, dsl_hash 42e29a62, delta_sem=0.10, qhat=0.4847",
             generator_version=V4GEN,
             split_id="cluster bootstrap over 464 test clusters, 2000 resamples",
             n=t4["n_units"],
             value=dig(t4, "rho_e2e/point"),
             ci=[dig(t4, "rho_e2e/lo"), dig(t4, "rho_e2e/hi")]),
        dict(campaign_id="V6 calibrated",
             metric="licensed-and-retained target",
             population="frozen cross-organization e2e test split",
             denominator="grammar-reachable (DSL-expressible) test units",
             conditioning="target expressible in the DSL",
             scorer_id="frozen v3 weights + semantic licensing, qhat=0.362",
             generator_version="LM semantic licenser, k=16, v5 documentation catalog",
             split_id="same frozen test split; no CI archived",
             n=v6["test"]["n"],
             value=dig(v6, "test/rho_e2e"),
             ci=None),
        dict(campaign_id="Three-repository replication",
             metric="in-DSL leave-one-out coverage",
             population="220 in-DSL rules from three unseen repositories",
             denominator="in-DSL rules (151 out-of-DSL units excluded; "
                         "including them gives 0.542)",
             conditioning="target in-DSL",
             scorer_id="frozen benchmark scorer, delta_sem=0.10",
             generator_version="frozen benchmark generator",
             split_id="leave-one-out over rules; Clopper-Pearson "
                      "(cluster bootstrap [0.852, 0.952] also archived)",
             n=dig(ext, "primary_iid_loo/n_test"),
             value=dig(ext, "primary_iid_loo/in_dsl_coverage"),
             ci=dig(ext, "primary_iid_loo/in_dsl_cov_cp")),
    ]

    # The plan's rule, enforced mechanically: a composition of two rows is
    # emitted ONLY if this guard passes.  It is called on every pair that the
    # paper composes, and (below) on every pair the paper must NOT compose,
    # to prove the guard actually discriminates.
    def composable(i, j) -> bool:
        a, b = rows[i], rows[j]
        return (a["campaign_id"] == b["campaign_id"]
                and a["population"] == b["population"]
                and a["scorer_id"] == b["scorer_id"]
                and a["generator_version"] == b["generator_version"]
                # chaining is legal only when row j explicitly declares that
                # it conditions on row i's success event
                and b.get("conditions_on") == f"{a['campaign_id']}/{a['metric']}")

    def compose(i, j) -> float:
        if not composable(i, j):
            raise SystemExit(
                f"P0-A: refusing to combine rows {i} and {j}: "
                f"{rows[i]['campaign_id']}/{rows[i]['denominator']} vs "
                f"{rows[j]['campaign_id']}/{rows[j]['denominator']}")
        return rows[i]["value"] * rows[j]["value"]

    # V4 generation x V4 retention: same campaign, split, scorer and
    # generator, and retention conditions on generation.  This is the only
    # composition the paper prints.
    composed = compose(1, 2)
    # Guard discrimination check: the tempting cross-campaign products must be
    # rejected.  E0-T generation x V4 retention, and V6 licensing x V4
    # retention, are exactly the confusions the plan warns about.
    for bad in ((0, 2), (4, 2), (1, 4)):
        assert not composable(*bad), \
            f"P0-A guard failed to reject illegal composition {bad}"

    os.makedirs(ACC_DIR, exist_ok=True)
    json.dump(dict(rows=rows,
                   legal_composition=dict(
                       what="V4 generation x V4 retention-given-generation",
                       value=composed,
                       equals_fraction_of_expressible_targets_retained=True),
                   warning="Rows with different populations/denominators must "
                           "never be multiplied or compared.",
                   ),
              open(os.path.join(ACC_DIR, "semantic_accounting.json"), "w"), indent=1)
    cols = ["campaign_id", "metric", "population", "denominator", "conditioning",
            "scorer_id", "generator_version", "split_id", "n", "value", "ci"]
    with open(os.path.join(ACC_DIR, "semantic_accounting.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=cols)
        w.writeheader()
        for r in rows:
            w.writerow({c: r.get(c) for c in cols})
    print("wrote", os.path.join(ACC_DIR, "semantic_accounting.csv"))

    body = []
    for r in rows:
        ci = ("--" if r["ci"] is None
              else f"$[{r['ci'][0]:.3f},{r['ci'][1]:.3f}]$")
        body.append(
            f"{r['campaign_id']} & {r['metric']} & {r['conditioning']} & "
            f"${r['n']}$ & ${r['value']:.3f}$ & {ci} \\\\\n")
    write("gen_semantic_accounting.tex", "".join(body))

    # P0-A also requires the FULL-provenance serialization: the same rows with
    # every field, written to results/paper/semantic_accounting.tex (the third
    # member of the {csv,json,tex} triple) and to a generated fragment the
    # appendix typesets.
    def _tx(x):
        return (str(x).replace("\\", "").replace("_", r"\_")
                .replace("%", r"\%").replace("&", r"\&"))

    full = []
    for r in rows:
        ci = ("--" if r["ci"] is None
              else f"$[{r['ci'][0]:.3f},{r['ci'][1]:.3f}]$")
        full.append(" & ".join([
            _tx(r["campaign_id"]), _tx(r["population"]), _tx(r["denominator"]),
            _tx(r["conditioning"]), _tx(r["scorer_id"]),
            _tx(r["generator_version"]), _tx(r["split_id"]),
            f"${r['n']}$", _tx(r["metric"]), f"${r['value']:.3f}$", ci,
        ]) + " \\\\\n")
    with open(os.path.join(ACC_DIR, "semantic_accounting.tex"), "w") as fh:
        fh.write("".join(full))
    print("wrote", os.path.join(ACC_DIR, "semantic_accounting.tex"))
    write("gen_semantic_accounting_full.tex", "".join(full))
    return rows, composed


