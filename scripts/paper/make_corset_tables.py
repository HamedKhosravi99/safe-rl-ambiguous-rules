def gen_m5_coverage():
    """Table 7's data rows. This fragment was committed with an
    "AUTO-GENERATED" header and no writer anywhere in the repo, which made
    the reproducibility statement's "no number in a table is
    hand-transcribed" untrue for the paper's own headline coverage table.
    The values were right; nothing could regenerate them. This does."""
    f = os.path.join(ROOT, "results", "corpus_eval", "test_report_openai.json")
    if not os.path.exists(f):
        return pending("gen_m5_coverage.tex", "M5 test report absent")
    from scipy.stats import beta
    d = json.load(open(f))

    def cp(cov):
        ci = cov.get("clopper_pearson_ci95")
        if ci:
            return ci[0], ci[1]
        n, c = cov["n"], cov["covered"]
        return (float(beta.ppf(0.025, c, n - c + 1)),
                float(beta.ppf(0.975, c + 1, n - c)))

    def row(label, blk):
        cov = blk["coverage"]
        lo, hi = cp(cov)
        return (f"{label} & {cov['n']} & {blk['coverage_in_dsl']['rate']:.3f} & "
                f"{cov['rate']:.3f}~[{lo:.3f}, {hi:.3f}] & "
                f"{blk['set_size']['mean']:.2f} & "
                f"{blk['set_size_reduction_vs_constant']*100:.0f}\\% & "
                f"{blk['escalation']['out_of_dsl_recall']:.2f} \\\\\n")

    rows = (row("Test (iid)", d["test"])
            + row("Transfer: held-out generator", d["transfer_heldout_generator"])
            + row("Transfer: held-out domain", d["transfer_heldout_domain_battery"]))
    assert rows.count("\\\\") == 3, rows
    write("gen_m5_coverage.tex", rows)


def gen_certprice():
    """Certified relative price of ambiguity, from a single LP convention.

    Both the numerator and the denominator are read from the subset-LP
    values in shadow_price.json (set-independent per-reading normalization),
    so no ratio mixes normalization conventions:
        PoA = max_psi V_{psi} - V_{Uhat},  rel = PoA / max_psi V_{psi}.
    """
    f = os.path.join(ROOT, "results/conformal", "lp", "shadow_price.json")
    if not os.path.exists(f):
        return pending("gen_certprice.tex", "shadow_price.json missing")
    doms = json.load(open(f))["domains"]
    rels = {}
    for name, v in doms.items():
        t = v["t1_exact_minimax"]
        vs = t["V_by_subset"]
        M = t["M"]
        singles = [val for k, val in vs.items() if k != "(none)" and "+" not in k]
        full = [val for k, val in vs.items() if k.count("+") == M - 1]
        v_max, v_u = max(singles), full[0]
        poa = v_max - v_u
        rels[name] = 100.0 * poa / v_max
    lo, hi = min(rels.values()), max(rels.values())
    # pin against the exact-LP prices reported in tab:lp
    assert abs(rels["gridworld"] - 1.262) < 0.02, rels
    assert abs(rels["budget"] - 20.879) < 0.02, rels
    write("gen_certprice.tex",
          f"\\newcommand{{\\certRelLo}}{{{lo:.1f}\\%}}\n"
          f"\\newcommand{{\\certRelHi}}{{{hi:.1f}\\%}}\n")

    # The abstract quotes lo--hi; without the components a reader cannot
    # check either endpoint, so emit the numerator and denominator per
    # domain under the same single LP convention.
    rows = []
    for name in sorted(doms):
        t = doms[name]["t1_exact_minimax"]
        vs, M = t["V_by_subset"], t["M"]
        singles = [val for k, val in vs.items() if k != "(none)" and "+" not in k]
        full = [val for k, val in vs.items() if k.count("+") == M - 1][0]
        v_max = max(singles)
        rows.append(f"{DOM_LABEL.get(name, name)} & ${v_max:.2f}$ & ${full:.2f}$ & "
                    f"${v_max - full:.2f}$ & ${100.0 * (v_max - full) / v_max:.1f}$ \\\\\n")
    write("gen_certprice_table.tex", "".join(rows))


