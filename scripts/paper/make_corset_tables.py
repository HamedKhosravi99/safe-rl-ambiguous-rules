def gen_opscope_compact():
    """A two-column body version of the operative-scope table, emitted from the
    appendix table itself so the rows cannot drift apart.

    The full three-column table does not fit in a 9-page body -- it overruns by
    17 lines even with a four-line caption. Hand-copying its rows into a
    compact duplicate is exactly the transcription risk this project keeps
    getting bitten by, so the compact version is generated from the same source
    and asserted to carry every row."""
    src = os.path.join(ROOT, "paper", "corset_iclr_appendix_short.tex")
    if not os.path.exists(src):
        return pending("gen_opscope_compact.tex", "appendix source missing")
    t = open(src).read()
    i = t.find("\\label{tab:opscope}")
    if i < 0:
        return pending("gen_opscope_compact.tex", "tab:opscope not found")
    a = t.find("\\midrule", i)
    b = t.find("\\bottomrule", a)
    rows = []
    for line in t[a:b].split("\\\\"):
        cells = [c.strip() for c in line.split("&")]
        if len(cells) < 2:
            continue
        res = cells[0].replace("\\midrule", "").strip()
        if not res:
            continue
        rows.append(f"{res} & {cells[1].strip()} \\\\\n")
    assert len(rows) >= 8, f"expected the full ledger, parsed {len(rows)}"
    n_not = sum(1 for r in rows if "not exercised" in r)
    n_part = sum(1 for r in rows if "partly" in r)
    assert n_not == 1 and n_part == 4, (n_not, n_part)
    # two logical rows per printed line: the body table is set two-up
    cells = [r.replace(" \\\\\n", "") for r in rows]
    if len(cells) % 2:
        cells.append(" & ")
    paired = "".join(f"{cells[i]} & {cells[i+1]} \\\\\n"
                     for i in range(0, len(cells), 2))
    write("gen_opscope_compact.tex", paired)
    write("gen_opscope_counts.tex",
          f"\\newcommand{{\\opsNot}}{{{n_not}}}\n"
          f"\\newcommand{{\\opsPartly}}{{{n_part}}}\n"
          f"\\newcommand{{\\opsTotal}}{{{len(rows)}}}\n")


