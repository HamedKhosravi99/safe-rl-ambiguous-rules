# E2 kill test (fqi from risk50+budget50; cql rows from main50 when present)
# --------------------------------------------------------------------------
def gen_kill():
    risk, budget, main = load("risk50"), load("budget50"), load("main50")
    if risk is None or budget is None:
        return pending("gen_kill.tex", "risk50/budget50 not finished")

    def pm(blob, key):
        return blob["summary"]["per_model"].get(key)

    def paired(blob, key):
        return blob["summary"]["paired"].get(key)

    rows = []
    for dom in ("synthetic", "real", "gridworld", "budget"):
        blob = budget if dom == "budget" else risk
        cql = main if (main and dom in ("synthetic", "real")) else None
        nlearn = 2 if cql else 1
        nrows = 1 + 2 * nlearn
        rows.append(f"\\multirow{{{nrows}}}{{*}}{{{DOM_LABEL[dom]}}}")
        un = pm(blob, f"{dom}/unconstrained")
        rows.append(f" & Return-greedy & {fmt1(un['ret'])} & --- & {fmt(un['true_worst'])} & --- & \\\\\n")
        for lname, ltag, src in (("fqi", "FQI", blob), ("cql", "CQL", cql)):
            if src is None:
                continue
            s = pm(src, f"{dom}/{lname}:single")
            r = pm(src, f"{dom}/{lname}:saorl")
            p = paired(src, f"{dom}/{lname}")
            gap = s["true_worst"][0] - s["honored"][0]
            wil = f"\\multirow{{2}}{{*}}{{\\,{pfmt(p['wilcoxon_p'])}, {p['n_separate']}/{p['n']}}}"
            rows.append(f" & Single ({ltag}) & {fmt1(s['ret'])} & {fmt(s['honored'])} & "
                        f"{fmt(s['true_worst'])} & ${gap:.3f}$ & {wil} \\\\\n")
            rows.append(f" & \\corset{{}} ({ltag}) & {fmt1(r['ret'])} & {fmt(r['honored'])} & "
                        f"{fmt(r['true_worst'])} & --- & \\\\\n")
        rows.append("\\midrule\n" if dom != "budget" else "")
    write("gen_kill.tex", "".join(rows))


def gen_kill_compact():
    """Short-build kill table: the Single-vs-CORSET contrast only.

    Same archived run files as gen_kill(); the unconstrained return-greedy
    reference and the CQL neural replication rows are dropped for space and
    stated in the full version. No number is re-derived here.
    """
    risk, budget = load("risk50"), load("budget50")
    if risk is None or budget is None:
        return pending("gen_kill_compact.tex", "risk50/budget50 not finished")
    rows = []
    for dom in ("synthetic", "real", "gridworld", "budget"):
        blob = budget if dom == "budget" else risk
        s_ = blob["summary"]["per_model"][f"{dom}/fqi:single"]
        r_ = blob["summary"]["per_model"][f"{dom}/fqi:saorl"]
        p_ = blob["summary"]["paired"][f"{dom}/fqi"]
        gap = s_["true_worst"][0] - s_["honored"][0]
        assert gap > 0, (dom, gap)                    # the hidden gap must be real
        assert r_["true_worst"][0] <= 0.05, (dom, r_["true_worst"])
        wil = f"\\multirow{{2}}{{*}}{{\\,{pfmt(p_['wilcoxon_p'])}, {p_['n_separate']}/{p_['n']}}}"
        rows.append(f"\\multirow{{2}}{{*}}{{{DOM_LABEL[dom]}}}")
        rows.append(f" & Single & {fmt1(s_['ret'])} & {fmt(s_['honored'])} & "
                    f"{fmt(s_['true_worst'])} & ${gap:.3f}$ & {wil} \\\\\n")
        rows.append(f" & \\corset{{}} & {fmt1(r_['ret'])} & {fmt(r_['honored'])} & "
                    f"{fmt(r_['true_worst'])} & --- & \\\\\n")
        rows.append("\\midrule\n" if dom != "budget" else "")
    write("gen_kill_compact.tex", "".join(rows))


