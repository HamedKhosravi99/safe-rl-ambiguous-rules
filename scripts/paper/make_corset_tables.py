"""Generate LaTeX table bodies for the CORSET paper from result JSONs.

Every numeric cell in corset_experiments.tex is \\input from paper/generated/,
written by this script -- no hand-transcribed numbers. Sources:

  results/conformal/risk50/    fqi kill test + primary risk, 50 seeds (synthetic, real, gridworld)
  results/conformal/budget50/  fqi kill test + risk, budget, 50 seeds
  results/conformal/main50/    fqi+cql kill test, 50 seeds (adds the CQL rows)
  results/conformal/agnostic50/ fqi,cpq,pid on synthetic, 50 seeds
  results/conformal/cmapss4/   FD001-FD004, 15 seeds
  results/conformal/extra30/   aggregation baselines, 30 seeds (E5 frontier)
  results/conformal/price/     price-of-ambiguity report, 15 seeds
  results/paper_extra/conformal/     conformal construction report (E1)

Missing sources emit a visible PENDING row so an un-finished build is
detectable in the compiled PDF.

Run:  python3 paper/make_corset_tables.py
"""
from __future__ import annotations

import glob
import json
import re
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GEN = os.path.join(ROOT, "paper", "generated")
os.makedirs(GEN, exist_ok=True)

DOM_LABEL = {
    "synthetic": "Maint.\\ (synthetic)",
    "real": "Maint.\\ (C-MAPSS)",
    "gridworld": "Warning-window",
    "budget": "Budget agent",
}


def newest(dirname):
    files = glob.glob(os.path.join(ROOT, "results/conformal", dirname, "experiments_*.json"))
    return max(files, key=os.path.getmtime) if files else None


def load(dirname):
    f = newest(dirname)
    return json.load(open(f)) if f else None


def fmt(pair, nd=3):
    if pair is None or pair[0] is None:
        return "--"
    return f"${pair[0]:.{nd}f}\\pm{pair[1]:.{nd}f}$"


def fmt1(pair):
    return fmt(pair, nd=1)


def pfmt(p):
    if p is None:
        return "--"
    if p <= 0:
        return "$0$"
    e = math.floor(math.log10(p))
    m = p / 10 ** e
    if abs(m - 1.0) < 0.05:
        return f"$10^{{{e}}}$"
    return f"${m:.1f}{{\\times}}10^{{{e}}}$"


def write(name, text):
    path = os.path.join(GEN, name)
    with open(path, "w") as fh:
        fh.write("% AUTO-GENERATED by paper/make_corset_tables.py -- do not edit\n")
        fh.write(text)
    print(f"wrote {path}")


def pending(name, msg):
    write(name, f"\\multicolumn{{2}}{{l}}{{\\textbf{{PENDING: {msg}}}}}\\\\\n")


