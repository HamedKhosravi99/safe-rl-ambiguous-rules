def gen_bind():
    """WHEN does set defense bind on real rules? (review #32, item b)

    Rather than reporting 5/17 at one budget and 1/17 at another, this
    characterizes the requirement per instance: an instance needs set defense at
    budget d exactly when no singleton gets its worst-reading cost to d. On this
    suite that is a function of the cap geometry, and it is monotone in d."""
    f = os.path.join(ROOT, "results/conformal", "benchmark_sg", "control_suite.json")
    if not os.path.exists(f):
        return pending("gen_bind.tex", "control suite missing")
    d = json.load(open(f))
    _vf = os.path.join(ROOT, "results/e2e", "exact_nonnested.json")
    if not os.path.exists(_vf):
        return pending("gen_bind.tex", "exact_nonnested (value screen) not run")
    _val = {r["uid"]: r["budgets"] for r in json.load(open(_vf))["instances"]}
    grid = ["0.005", "0.01", "0.02", "0.05"]
    by_geo = {}
    prof_all = []
    for ins in d["instances"]:
        # P0-D: the shipped verdict must be the tie-safe VALUE screen
        # (min_psi V_psi > V_U), not a predicate read off one representative
        # singleton optimum.  Values come from the archived exact study.
        prof = [bool(_val[ins["uid"]][g]["fires_value"]) for g in grid]
        prof_all.append(prof)
        by_geo.setdefault(ins["geometry"], []).append(prof)
    # the requirement must be monotone in the budget, else the story is wrong
    assert all(all(p[i] >= p[i + 1] for i in range(len(grid) - 1))
               for p in prof_all), "non-monotone in budget"
    # and constant within a geometry, which is the finding
    for g, ps in by_geo.items():
        assert all(p == ps[0] for p in ps), f"geometry {g} not homogeneous"
    rows = []
    for geo in sorted(by_geo, key=lambda g: -sum(by_geo[g][0])):
        ps = by_geo[geo][0]
        rows.append(f"\\texttt{{{geo}}} & {len(by_geo[geo])} & "
                    + " & ".join("\\cmark" if x else "\\xmark" for x in ps)
                    + " \\\\\n")
    write("gen_bind.tex", "".join(rows))
    n_always = sum(len(v) for g, v in by_geo.items() if all(v[0]))
    n_never = sum(len(v) for g, v in by_geo.items() if not any(v[0]))
    write("gen_bind_caption.tex",
          f"\\newcommand{{\\bindGeoms}}{{{len(by_geo)}}}\n"
          f"\\newcommand{{\\bindAlways}}{{{n_always}}}\n"
          f"\\newcommand{{\\bindNever}}{{{n_never}}}\n")


