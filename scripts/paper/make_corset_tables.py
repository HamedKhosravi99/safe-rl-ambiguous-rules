# E4 price of ambiguity (from price_report.json)
# --------------------------------------------------------------------------
def gen_price():
    f = os.path.join(ROOT, "results/conformal", "price", "price_report.json")
    if not os.path.exists(f):
        return pending("gen_price.tex", "price report not finished")
    r = json.load(open(f))
    rows = []
    rels = {}
    for dom in ("synthetic", "real", "gridworld", "budget"):
        v = r["domains"].get(dom)
        if v is None:
            continue
        a = v["agg"]
        row0 = v["rows"][0]
        usize = len(row0["u_names"])
        vor = max(p["v_psi"] for p in row0["per_psi"])
        rel = 100.0 * a["wpoa_realized"] / abs(vor) if vor else 0.0
        rels[dom] = rel
        rows.append(
            f"{DOM_LABEL[dom]} & {usize} & "
            f"${a['wpoa_realized']:.2f}\\pm{a['wpoa_realized_sd']:.2f}$ & "
            f"${a['wpoa_surgery']:.2f}\\pm{a['wpoa_surgery_sd']:.2f}$ & "
            f"${a['wpoa_predicted']:.0f}$ & "
            f"${rel:.1f}\\%$ & "
            f"${a['voq']:.2f}\\pm{a['voq_sd']:.2f}$ & "
            f"{a['bound_violations']}/{a['n_bound_checks']} \\\\\n")
    write("gen_price.tex", "".join(rows))
    # The abstract quotes the CERTIFIED (LP-optimal) price range; the learned
    # pipeline delivers a different range, and reviewers rightly asked for both.
    # Emitted here so the two can never drift apart.
    lo, hi = min(rels.values()), max(rels.values())
    assert abs(rels["real"] - 24.4) < 0.15, rels          # C-MAPSS, the gap case
    assert abs(rels["synthetic"] - 0.6) < 0.15, rels
    write("gen_delivered.tex",
          f"\\newcommand{{\\delivRelLo}}{{{lo:.1f}\\%}}\n"
          f"\\newcommand{{\\delivRelHi}}{{{hi:.1f}\\%}}\n"
          f"\\newcommand{{\\delivRelCmapss}}{{{rels['real']:.1f}\\%}}\n")


