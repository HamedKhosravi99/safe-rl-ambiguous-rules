def gen_calibmatters():
    """Conformal retention against a fixed tau=0.5 gate on real artifacts.

    The comparison the mechanism has to survive: if the calibrated threshold
    coincides with a hand-set gate, the conformal layer is decoration. Numbers
    are read from the leave-one-out sweep; nothing is re-derived here.
    """
    p = os.path.join(ROOT, "results/conformal", "benchmark_sg",
                     "calib_vs_fixed.json")
    if not os.path.exists(p):
        return pending("gen_calibmatters.tex", "calibration sweep not run")
    d = json.load(open(p))
    ag = {(a["family"], round(a["delta"], 2)): a for a in d["aggregates"]}
    fam_label = {"prometheus": "Prometheus", "kyverno": "Kyverno"}
    rows = []
    for fam in ("prometheus", "kyverno"):
        for i, dl in enumerate((0.05, 0.10, 0.15, 0.20)):
            a = ag[(fam, dl)]
            lead = f"\\multirow{{4}}{{*}}{{{fam_label[fam]}}}" if i == 0 else ""
            rows.append(
                f"{lead} & ${dl:.2f}$ & ${a['qhat_min']:.3f}$--${a['qhat_max']:.3f}$ & "
                f"${a['pct_sets_differ']:.0f}$ & ${a['saves']}$ & ${a['losses']}$ & "
                f"${a['coverage_conf']:.3f}$ & ${a['coverage_fix']:.3f}$ \\\\\n")
        rows.append("\\midrule\n" if fam == "prometheus" else "")
    write("gen_calibmatters.tex", "".join(rows))

    # the mechanism must be distinguishable from the hand-set gate
    assert all(a["qhat_max"] < 0.5 for a in d["aggregates"]), "qhat pinned at the gate"
    assert all(a["losses"] == 0 for a in d["aggregates"]), "calibration lost a target"
    lo = min(a["pct_sets_differ"] for a in d["aggregates"])
    hi = max(a["pct_sets_differ"] for a in d["aggregates"])
    cf = [a for a in d["aggregates"] if abs(a["delta"] - 0.10) < 1e-9]
    write("gen_calibmatters_macros.tex",
          "\\newcommand{\\cmDifferLo}{" + f"{lo:.0f}\\%" + "}\n"
          "\\newcommand{\\cmDifferHi}{" + f"{hi:.0f}\\%" + "}\n"
          "\\newcommand{\\cmQhatLo}{" + f"{min(a['qhat_min'] for a in d['aggregates']):.3f}" + "}\n"
          "\\newcommand{\\cmQhatHi}{" + f"{max(a['qhat_max'] for a in d['aggregates']):.3f}" + "}\n"
          "\\newcommand{\\cmCovConf}{" + f"{min(a['coverage_conf'] for a in cf):.3f}" + "}\n"
          "\\newcommand{\\cmCovFix}{" + f"{max(a['coverage_fix'] for a in d['aggregates']):.3f}" + "}\n"
          "\\newcommand{\\cmSaves}{" + f"{sum(a['saves'] for a in cf)}" + "}\n")


if __name__ == "__main__":
    gen_calibmatters()


def gen_matchedsize():
    """Conformal vs the best TUNED constant at matched mean set size.

    The tau=0.5 comparison is one-sided by construction. Holding set size
    fixed and tuning the constant is the honest test, and it comes out a
    dead heat: what calibration buys is the guarantee without a tuning
    oracle, not extra coverage.
    """
    p = os.path.join(ROOT, "results/conformal", "benchmark_sg", "matched_size.json")
    if not os.path.exists(p):
        return pending("gen_matchedsize.tex", "matched-size sweep not run")
    d = json.load(open(p))
    fam = {"prometheus": "Prometheus", "kyverno": "Kyverno"}
    rows = []
    for i, r in enumerate(d):
        lead = (f"\\multirow{{4}}{{*}}{{{fam[r['family']]}}}"
                if i % 4 == 0 else "")
        rows.append(f"{lead} & ${r['delta']:.2f}$ & ${r['conf_mean_size']:.2f}$ & "
                    f"${r['conf_coverage']:.3f}$ & ${r['tuned_tau']:.3f}$ & "
                    f"${r['tuned_coverage']:.3f}$ & ${r['coverage_delta']:+.3f}$ \\\\\n")
        if i == 3:
            rows.append("\\midrule\n")
    write("gen_matchedsize.tex", "".join(rows))
    gaps = [abs(r["coverage_delta"]) for r in d]
    assert max(gaps) < 1e-9, ("matched-size coverage is no longer a dead heat", gaps)
    write("gen_matchedsize_macros.tex",
          "\\newcommand{\\msCells}{" + str(len(d)) + "}\n"
          "\\newcommand{\\msMaxGap}{" + f"{max(gaps):.3f}" + "}\n")


if __name__ == "__main__":
    gen_matchedsize()


