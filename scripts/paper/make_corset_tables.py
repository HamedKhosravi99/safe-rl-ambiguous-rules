# --------------------------------------------------------------------------
# E2c C-MAPSS subsets (cmapss4, 15 seeds): per subset single->saorl + flips
# --------------------------------------------------------------------------
def gen_cmapss4():
    blob = load("cmapss4")
    if blob is None:
        return pending("gen_cmapss4.tex", "cmapss4 not finished")
    meta = {"real": ("FD001", 1, 1, 100), "real_FD002": ("FD002", 6, 1, 260),
            "real_FD003": ("FD003", 1, 2, 100), "real_FD004": ("FD004", 6, 2, 249)}
    recs = blob["records"]
    eps = blob["config"]["eps"]
    rows = []
    for dom, (name, reg, fault, eng) in meta.items():
        single = {r["seed"]: r for r in recs if r["domain"] == dom and r["model"] == "fqi:single"}
        saorl = {r["seed"]: r for r in recs if r["domain"] == dom and r["model"] == "fqi:saorl"}
        if not single:
            continue
        seeds = sorted(single)
        ws = [single[s]["true_worst"] for s in seeds]
        wr = [saorl[s]["true_worst"] for s in seeds]
        deltas = [a - b for a, b in zip(ws, wr)]
        flips = sum(1 for a, b in zip(ws, wr) if a > eps >= b)
        ch_s = sum(single[s]["chance"] for s in seeds) / len(seeds)
        ch_r = sum(saorl[s]["chance"] for s in seeds) / len(seeds)
        import statistics as st
        dm = st.mean(deltas)
        dsd = 1.96 * st.pstdev(deltas) / math.sqrt(len(deltas)) if len(deltas) > 1 else 0.0
        usz = 3 if name != "FD002" else 2
        p = blob["summary"]["paired"].get(f"{dom}/fqi", {}).get("wilcoxon_p")
        rows.append(
            f"{name} & {reg} & {fault} & {eng} & {usz} & "
            f"${st.mean(ws):.3f}\\!\\to\\!{st.mean(wr):.3f}$ & ${dm:+.3f}{{\\pm}}{dsd:.3f}$ & "
            f"{pfmt(p)} & ${flips}/{len(seeds)}$ & ${ch_s:.2f}\\!\\to\\!{ch_r:.2f}$ \\\\\n")
    write("gen_cmapss4.tex", "".join(rows))


# --------------------------------------------------------------------------
# E5 frontier: does ANY safe policy beat CORSET's return? (risk50+extra30 zoo)
# --------------------------------------------------------------------------
def gen_frontier():
    risk, extra, budget = load("risk50"), load("extra30"), load("budget50")
    if risk is None or budget is None:
        return pending("gen_frontier.tex", "risk50/budget50 not finished")
    eps = risk["config"]["eps"]
    pools = [r for src in (risk, extra, budget) if src for r in src["records"]]
    import statistics as st
    rows = []
    for dom in ("synthetic", "real", "gridworld", "budget"):
        recs = [r for r in pools if r["domain"] == dom]
        if not recs:
            continue
        # model-level safety: a policy CLASS counts as safe iff its mean
        # worst-case cost meets the budget (per-seed cherry-picking would
        # compare an infeasible deployment rule).
        by_model = {}
        for r in recs:
            by_model.setdefault(r["model"], []).append(r)
        v_r = st.mean([r["ret"] for r in by_model["fqi:saorl"]])
        safe = {m: v for m, v in by_model.items()
                if m != "fqi:saorl" and st.mean([x["true_worst"] for x in v]) <= eps}
        if safe:
            best_model, best_ret = max(((m, st.mean([x["ret"] for x in v]))
                                        for m, v in safe.items()), key=lambda kv: kv[1])
            margin = best_ret - v_r
            safe_model = best_model.replace("_", "-")
            rows.append(f"{DOM_LABEL[dom]} & ${v_r:.1f}$ & {safe_model} & "
                        f"${best_ret:.1f}$ & ${margin:+.2f}$ \\\\\n")
        else:
            rows.append(f"{DOM_LABEL[dom]} & ${v_r:.1f}$ & none & --- & --- \\\\\n")
    write("gen_frontier.tex", "".join(rows))


# --------------------------------------------------------------------------
# Appendix: aggregation collapses (extra30) -- conservative/majority/expected/
# quantile vs CORSET, paired worst-case gaps
# --------------------------------------------------------------------------
def gen_aggregations():
    blob = load("extra30")
    if blob is None:
        return pending("gen_aggregations.tex", "extra30 not finished")
    paired = blob["summary"]["paired"]
    label = {"single": "Single (most plausible)", "conservative": "conservative ($\\psi^\\star$)",
             "majority": "majority (consensus)", "expected": "expected (mean)",
             "quantile": "quantile ($q{=}0.9$)"}
    doms = [("synthetic", "Maint.\\ (synthetic)"), ("real", "C-MAPSS (real)"),
            ("gridworld", "Warning-window")]
    rows = []
    for dom, dlabel in doms:
        keys = [k for k in paired if k.startswith(f"{dom}/fqi/vs_")]
        # fall back: aggregation baselines may be logged as models in per_model
        pm = blob["summary"]["per_model"]
        agg_models = [m.split(":", 1)[1] for m in
                      (k.split("/", 1)[1] for k in pm if k.startswith(f"{dom}/fqi:"))
                      if m.split(":", 1)[1] in label]
        if not agg_models:
            continue
        saorl_tw = pm[f"{dom}/fqi:saorl"]["true_worst"]
        shown = [m for m in ("single", "conservative", "majority", "expected", "quantile")
                 if m in agg_models or m == "single"]
        rows.append(f"\\multirow{{{len(shown)}}}{{*}}{{{dlabel}}}")
        for m in shown:
            key = f"{dom}/fqi:{m}" if m != "single" else f"{dom}/fqi:single"
            if key not in pm:
                continue
            tw = pm[key]["true_worst"]
            gap = tw[0] - saorl_tw[0]
            note = "coincides" if abs(gap) < 5e-4 else f"${gap:+.3f}$"
            rows.append(f" & {label[m]} & {fmt(tw)} & {note} \\\\\n")
        rows.append("\\midrule\n" if dom != "gridworld" else "")
    write("gen_aggregations.tex", "".join(rows))


# --------------------------------------------------------------------------
# E3: DSRL/OSRL merged table (seeds 0-2 committed sweeps + 3-4 cluster extension;
# optional most-plausible c*=20 arm from ext_mp20). Also prints the violating-
# cell recount used in the prose.
# --------------------------------------------------------------------------
def _dedup_runs(records, key_fields):
    """Keep exactly one record per key so a seed present in more than one
    results dir (base sweep + 20-seed top-up, or a straggler resubmit) is NOT
    counted twice in mean/std. Deterministic: callers sort the file order, so
    last-write-wins is stable (duplicates are the same computation -> same
    values). Records missing a key field are dropped."""
    out = {}
    for r in records:
        try:
            k = tuple(r[f] for f in key_fields)
        except KeyError:
            continue
        out[k] = r
    return list(out.values())


def gen_dsrl():
    import statistics as st
    # The 20-seed primary arm (W21/W23) accumulated across SEVERAL cluster rounds:
    # the skip-guard only re-ran not-yet-both-ok cells, so a given (task,learner,
    # seed) lands in exactly one of topup/topup2/topup4/ext_p20seed. ALL of them
    # must be read or seeds are silently dropped. _dedup_runs removes the (large)
    # cross-round overlap, so adding dirs can only ADD seeds, never double-count.
    base_dirs = ["results/dsrl/sweep", "results/dsrl/sweep_caps",
                 "results/dsrl/sweep_cdt", "results/dsrl/sweep_coptidice",
                 "results/dsrl/ext_ext",
                 "results/dsrl/ext_p20seed", "results/dsrl/topup",
                 "results/dsrl/topup2", "results/dsrl/topup4"]
    recs = []
    for d in base_dirs:
        for f in sorted(glob.glob(os.path.join(ROOT, d, "**", "dsrl_sweep_*.json"),
                                  recursive=True)):
            blob = json.load(open(f))
            for r in blob.get("runs", []):
                if r.get("status") == "ok" and tuple(r.get("U", [])) == (10, 20, 40):
                    recs.append(r)
    mp = []
    for f in sorted(glob.glob(os.path.join(ROOT, "results/dsrl", "ext_mp20", "**",
                                           "dsrl_sweep_*.json"), recursive=True)):
        blob = json.load(open(f))
        for r in blob.get("runs", []):
            if (r.get("status") == "ok" and r.get("reading") == "single"
                    and r.get("target_cost") == 20):
                mp.append(r)
    # dedup by seed so base+top-up (or straggler resubmit) never double-count
    recs = _dedup_runs(recs, ("task", "learner", "reading", "seed"))
    mp = _dedup_runs(mp, ("task", "learner", "seed"))
    if not recs:
        return pending("gen_dsrl.tex", "no DSRL records found")

    tasks = ["OfflineAntRun-v0", "OfflineBallCircle-v0", "OfflineCarCircle-v0",
             "OfflineCarRun-v0", "OfflineDroneCircle-v0"]
    tlabel = {t: t.replace("Offline", "").replace("-v0", "") for t in tasks}
    learners = ["bcql", "cpq", "coptidice", "cdt", "caps"]
    llabel = {"bcql": "BCQ-Lagrangian", "cpq": "CPQ", "coptidice": "COptiDICE",
              "cdt": "CDT", "caps": "CAPS"}

    def cell(pool, task, learner, reading):
        rs = [r for r in pool if r["task"] == task and r["learner"] == learner
              and r["reading"] == reading]
        if not rs:
            return None
        rew = [r["normalized_reward"] for r in rs]
        cst = [r["worst_retained_normalized_cost"] for r in rs]
        return (st.mean(rew), st.pstdev(rew), st.mean(cst), st.pstdev(cst), len(rs))

    have_mp = bool(mp)
    rows, viol_cells, improved = [], 0, 0
    mp_viol, mp_overlap, exceptions = 0, 0, []
    for t in tasks:
        for ln in learners:
            s = cell(recs, t, ln, "single")
            a = cell(recs, t, ln, "saorl")
            m = cell(mp, t, ln, "single") if have_mp else None
            if s is None or a is None:
                continue
            if m and m[2] > 1.0:
                mp_viol += 1               # c=20 most-plausible violates strictest
            if s[2] > 1.0:
                viol_cells += 1            # c=40 loosest single violates
                if m and m[2] > 1.0:
                    mp_overlap += 1        # ...and c=20 also violates this cell
                if a[2] < s[2]:
                    improved += 1          # CORSET lowers the worst-retained cost
                else:
                    exceptions.append((tlabel[t], llabel[ln], s[2], a[2]))
            mp_rew = f"{m[0]:.2f}\\,$\\pm$\\,{m[1]:.2f}" if m else "--"
            mp_cst = f"{m[2]:.2f}\\,$\\pm$\\,{m[3]:.2f}" if m else "--"
            rows.append(
                f"{tlabel[t]} & {llabel[ln]} & "
                f"{s[0]:.2f}\\,$\\pm$\\,{s[1]:.2f} & {mp_rew} & "
                f"{a[0]:.2f}\\,$\\pm$\\,{a[1]:.2f} & "
                f"{s[2]:.2f}\\,$\\pm$\\,{s[3]:.2f} & {mp_cst} & "
                f"{a[2]:.2f}\\,$\\pm$\\,{a[3]:.2f} \\\\\n")
        rows.append("\\addlinespace\n" if t != tasks[-1] else "")
    write("gen_dsrl.tex", "".join(rows))

    # ---- data-driven seed-count labels (so no hand-edited "5 seeds" goes stale
    #      after the 20-seed merge; the caption \input's these macros) ----
    def _seed_text(pool, readings):
        percell = []
        for t in tasks:
            for ln in learners:
                for rd in readings:
                    ss = {r["seed"] for r in pool if r["task"] == t
                          and r["learner"] == ln and r["reading"] == rd}
                    if ss:
                        percell.append(len(ss))
        distinct = sorted({r["seed"] for r in pool})
        nd = len(distinct)
        if not percell:
            return "unavailable", nd
        lo, hi = min(percell), max(percell)
        if lo == hi:
            return f"{hi} seeds", nd
        return f"{lo}--{hi} seeds per cell ({nd} distinct)", nd

    main_txt, main_nd = _seed_text(recs, ("single", "saorl"))
    mp_txt, _mp_nd = _seed_text(mp, ("single",))
