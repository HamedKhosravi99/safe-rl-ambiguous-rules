def gen_shadow():
    f = os.path.join(ROOT, "results/conformal", "lp", "shadow_price.json")
    if not os.path.exists(f):
        return pending("gen_shadow.tex", "shadow_price study not run")
    r = json.load(open(f))
    pf = os.path.join(ROOT, "results/conformal", "price", "price_report.json")
    price = json.load(open(pf)) if os.path.exists(pf) else None
    rows = []
    ratios, raw_vacuous, tight_vacuous = [], 0, 0
    for dom in ("synthetic", "real", "gridworld", "budget"):
        if dom not in r["domains"]:
            continue
        t2 = r["domains"][dom]["t2_shadow_price"]
        closed = "--"
        if price is not None and dom in price["domains"]:
            closed = f"${price['domains'][dom]['agg']['wpoa_predicted']:.0f}$"
        t1 = r["domains"][dom]["t1_exact_minimax"]
        mm = {row["delta"]: row for row in t1["minimax"]}
        m05 = mm.get(0.05)
        resid = t2["tightness_gap"]
        resid_s = ("$0$ (exact)" if abs(resid) < 1e-3
                   else f"${resid:.1f}$")
        # Thm-lower bound at delta=0.05 under BOTH spans, derived from the
        # same archive: raw Delta_R (the theorem's stated span) and the
        # tightened span Dtilde = V_unconstrained - V_fullset (the Table-
        # `slack' convention).  Caption counts are derived here, never typed.
        M = t1["M"]
        vs = t1["V_by_subset"]
        v_unc = vs["(none)"]
