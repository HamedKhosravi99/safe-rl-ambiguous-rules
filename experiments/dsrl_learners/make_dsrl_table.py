#!/usr/bin/env python3
"""Merge DSRL sweep JSONs (incl. array-job arr_*/ subdirs) and emit the
SA-ORL-vs-SOTA table for the standard offline-safe-RL benchmark.

Story (per task x learner):
  single  = standard usage: honor the single most-plausible threshold c*=max(U)=40.
  SA-ORL  = our wrapper: honor the worst retained reading c_lo=min(U)=10.
We report normalized reward (matched) and the WORST-retained normalized cost
(=raw_cost/min(U)); single leaves it >1 (a true worst-case violation), SA-ORL
drives it <=1 (safe under every retained reading) -- the kill signal, on the
SAME benchmark + SAME learners the recent SOTA papers use.

Usage:
  python experiments/dsrl_learners/make_dsrl_table.py [results_dir]   # default results/dsrl
"""
import sys, os, glob, json, math
from collections import defaultdict

RESULTS_DIR = sys.argv[1] if len(sys.argv) > 1 else "results/dsrl"

# pretty task names (strip Offline.../-v0)
def short_task(t):
    return t.replace("Offline", "").replace("-v0", "")

# learner display names + canonical column order (Lagrangian, cost-critic+action
# restriction, stationary-distribution correction, return/cost-conditioned seq model)
LEARNER_LONG = {"bcql": "BCQ-Lagrangian", "cpq": "CPQ",
                "coptidice": "COptiDICE", "cdt": "CDT", "caps": "CAPS"}
LEARNER_ORDER = ["bcql", "cpq", "coptidice", "cdt", "caps"]


def mean_std(xs):
    xs = [x for x in xs if x is not None]
    if not xs:
        return float("nan"), float("nan")
    m = sum(xs) / len(xs)
    if len(xs) == 1:
        return m, 0.0
    v = sum((x - m) ** 2 for x in xs) / (len(xs) - 1)
    return m, math.sqrt(v)


def load_runs(results_dir):
    files = sorted(glob.glob(os.path.join(results_dir, "**", "dsrl_sweep_*.json"),
                             recursive=True))
    runs = []
    for f in files:
        try:
            blob = json.load(open(f))
        except Exception as e:
            print(f"[warn] skip {f}: {e}", file=sys.stderr)
            continue
        for r in blob.get("runs", []):
            if r.get("status") == "ok":
                runs.append(r)
    return runs, files


def aggregate(runs):
    # key (task, learner, reading) -> dict of lists across seeds
    G = defaultdict(lambda: defaultdict(list))
    seeds_seen = defaultdict(set)
    for r in runs:
        k = (r["task"], r["learner"], r["reading"])
        G[k]["nR"].append(r.get("normalized_reward"))
        G[k]["raw_cost"].append(r.get("raw_cost"))
        G[k]["worstNC"].append(r.get("worst_retained_normalized_cost"))
        G[k]["safe_all"].append(1.0 if r.get("satisfies_all_retained") else 0.0)
        seeds_seen[k].add(r.get("seed"))
    return G, seeds_seen


def fmt(m, s, prec=2):
    if math.isnan(m):
        return "--"
    return f"{m:.{prec}f}\\,$\\pm$\\,{s:.{prec}f}"


def main():
    runs, files = load_runs(RESULTS_DIR)
    print(f"# loaded {len(runs)} ok runs from {len(files)} file(s) under {RESULTS_DIR}/",
          file=sys.stderr)
    if not runs:
        print("# NO ok runs found -- nothing to tabulate.", file=sys.stderr)
        return
    G, seeds_seen = aggregate(runs)

    tasks = sorted({k[0] for k in G})
    learners = sorted({k[1] for k in G},
                      key=lambda l: LEARNER_ORDER.index(l) if l in LEARNER_ORDER else 99)

    # ---- human-readable summary ----
    print("# === SA-ORL vs single on DSRL/OSRL benchmark ===", file=sys.stderr)
    hdr = f"{'task':20} {'learner':6} {'read':7} {'n':>2}  {'nReward':>14} {'rawCost':>14} {'worstNC':>14} {'safe_all':>8}"
    print(hdr, file=sys.stderr)
    for t in tasks:
        for l in learners:
            for read in ("single", "saorl"):
                k = (t, l, read)
                if k not in G:
                    continue
                nrm, nrs = mean_std(G[k]["nR"])
                rcm, rcs = mean_std(G[k]["raw_cost"])
                wm, ws = mean_std(G[k]["worstNC"])
                sm, _ = mean_std(G[k]["safe_all"])
                n = len(seeds_seen[k])
                print(f"{short_task(t):20} {l:6} {read:7} {n:>2}  "
                      f"{nrm:6.3f}+-{nrs:5.3f} {rcm:6.2f}+-{rcs:5.2f} "
                      f"{wm:6.2f}+-{ws:5.2f} {sm:8.2f}", file=sys.stderr)

    # ---- LaTeX table ----
    print()
    print("% Auto-generated by experiments/dsrl_learners/make_dsrl_table.py -- DO NOT hand-edit numbers.")
    print("\\begin{table}[t]")
    print("\\centering")
    print("\\small")
    print("\\caption{\\textbf{SA-ORL on the standard DSRL/OSRL offline-safe-RL benchmark.} "
          "Each benchmark's own SOTA inner learner (BCQ-Lagrangian, CPQ) is selected by the "
          "identical offline rule under two readings of an ambiguous NL cost rule with retained "
          "set $U=\\{10,20,40\\}$: \\emph{single} honors the most-plausible threshold "
          "$c^\\star=40$; \\emph{SA-ORL} honors the worst retained reading $c_{\\mathrm{lo}}=10$. "
          "We report DSRL-normalized reward (higher better) and the worst-retained normalized "
          "cost $\\max_{c\\in U} C/c = C/10$ ($>1$ is a worst-case violation; $\\le 1$ is safe "
          "under every retained reading). In every cell where the single reading violates "
          "($>1$), SA-ORL lowers the worst-retained cost; where the inner learner can enforce the "
          "strict threshold it eliminates the violation at matched return (clearest for CPQ on "
          "CarCircle, $2.14{\\to}0.11$ at reward $0.73{\\to}0.68$). Residual violations (e.g.\\ "
          "BCQ-Lagrangian on the harder Ant/Drone tasks) and degenerate cells (CPQ collapses to "
          "near-zero return on AntRun/DroneCircle) reflect the \\emph{inner learner's} "
          "constraint-enforcement and offline-RL capacity on this data, not the audited set --- "
          "consistent with SA-ORL being learner-agnostic (Table~\\ref{tab:learner-agnostic}). "
          "Mean$\\pm$std over 3 seeds.}")
    print("\\label{tab:dsrl}")
    print("\\begin{tabular}{ll cc cc}")
    print("\\toprule")
    print(" & & \\multicolumn{2}{c}{Norm.\\ Reward $\\uparrow$} & "
          "\\multicolumn{2}{c}{Worst Norm.\\ Cost $\\downarrow$} \\\\")
    print("\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}")
    print("Task & Learner & single & SA-ORL & single & SA-ORL \\\\")
    print("\\midrule")
    for t in tasks:
        for l in learners:
            ks = (t, l, "single"); ka = (t, l, "saorl")
            if ks not in G and ka not in G:
                continue
            nr_s = mean_std(G[ks]["nR"]) if ks in G else (float("nan"), 0)
            nr_a = mean_std(G[ka]["nR"]) if ka in G else (float("nan"), 0)
            w_s = mean_std(G[ks]["worstNC"]) if ks in G else (float("nan"), 0)
            w_a = mean_std(G[ka]["worstNC"]) if ka in G else (float("nan"), 0)
            print(f"{short_task(t)} & {LEARNER_LONG.get(l, l)} & "
                  f"{fmt(*nr_s)} & {fmt(*nr_a)} & {fmt(*w_s)} & {fmt(*w_a)} \\\\")
    print("\\bottomrule")
    print("\\end{tabular}")
    print("\\end{table}")


if __name__ == "__main__":
    main()
