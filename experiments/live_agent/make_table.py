"""Phase 6 TABLE: demo/gen_demo.tex (paper section 22, phase 6).

Per-condition billed spend, task value, per-retained-reading violation rate, and
anchored-target violation rate, with paired 95% intervals -- all read from
logs/eval_summary.json (which is computed from the eval JSONL logs and the
billing records). NO hand-entered numbers.
"""
from __future__ import annotations

import json
from pathlib import Path

import readings as R

HERE = Path(__file__).resolve().parent
EVAL_SUMMARY = HERE / "logs" / "eval_summary.json"
VOQ_REPORT = HERE / "logs" / "voq_report.json"
TEX = HERE / "gen_demo.tex"

COND_ORDER = ["no_guard", "single", "corset", "post_clarify"]
COND_LABEL = {"no_guard": "no-guard (passthrough)", "single": "single ($k{=}5$)",
              "corset": "CORSET worst-retained ($k{=}3$)",
              "post\\_clarify": "post-clarify ($k{=}2$)",
              "post_clarify": "post-clarify ($k{=}2$)"}


def main():
    summ = json.loads(EVAL_SUMMARY.read_text())
    voq = json.loads(VOQ_REPORT.read_text())
    conds = summ["conditions"]
    rs = R.reading_sets()
    retained_ks = sorted(int(n.split(">=")[1]) for n in rs["retained_names"])
    anchor_k = R.ANCHOR_K

    col_ks = retained_ks
    ncol = 4 + len(col_ks) + 1
    lines = []
    lines.append("% Auto-generated by demo/make_table.py -- do not edit by hand.")
    lines.append("% All numbers from demo/logs/eval_summary.json + voq_report.json")
    lines.append("\\begin{tabular}{l" + "r" * (ncol - 1) + "}")
    lines.append("\\toprule")
    head = ["Condition", "billed \\$", "task value", "paid posts"]
    head += [f"$V\\psi_{{k={k}}}$" for k in col_ks]
    head += [f"$V$anchor($k{{=}}{anchor_k}$)"]
    lines.append(" & ".join(head) + " \\\\")
    lines.append("\\midrule")

    for c in COND_ORDER:
        s = conds[c]
        row = [COND_LABEL.get(c, c)]
        row.append(f"{s['billed_spend_total']:.5f}")
        row.append(f"{s['task_value_mean']:.2f}$\\pm${s['task_value_ci95']:.2f}")
        row.append(f"{s['n_paid_mean']:.1f}")
        for k in col_ks:
            d = s["retained_violation_rate"][f"psi_calls>={k}"]
            row.append(f"{d['rate']:.2f}$\\pm${d['ci95']:.2f}")
        a = list(s["anchored_target_violation_rate"].values())[0]
        row.append(f"{a['rate']:.2f}$\\pm${a['ci95']:.2f}")
        lines.append(" & ".join(row) + " \\\\")

    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")

    caption = (
        "\\caption{E8 live demonstration (policy "
        "\\texttt{real-a02-slack-posting-rate}, $\\hat q=0.5$, retained "
        "$U=\\{" + ",".join(f"\\psi_{{k\\ge {k}}}" for k in retained_ks)
        + "\\}$). "
        f"{summ['episodes_per_condition']} paired channel-session episodes per "
        "condition, real billed \\texttt{gpt-4o-mini} posts. Violation rate = "
        "episode-level chance the guarded agent posts past reading $\\psi_k$'s "
        "cap. The single-reading guard leaves the tighter retained readings "
        "violated; CORSET drives every retained reading to zero; asking recovers "
        "the strict anchor. "
        f"VoQ${{}}={voq['VoQ_plausibility']}$ vs $\\kappa={voq['kappa']}$ "
        f"return units (decision: {voq['decision']}).}}")

    # Caption above the tabular, matching every other table in the paper. When
    # it trailed the tabular it rendered below the rows and read as belonging
    # to the following float.
    head_comments, tabular = lines[:2], lines[2:]
    TEX.write_text("\n".join(head_comments) + "\n" + caption + "\n\n"
                   + "\n".join(tabular) + "\n")
    print(f"wrote {TEX.relative_to(HERE)}")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
